export function kanaMemory(entry: typeof kanaEntries[number], script: KanaScript = 'hiragana'): string {
  const specific = script === 'hiragana' ? memoryNotes[entry.id] : katakanaMemoryNotes[entry.id];
  if (specific) return specific;
  const glyph = entry[script];
  if (entry.group === 'voiced') {
    const base = glyph.normalize('NFD')[0];
    const mark = glyph.normalize('NFD').endsWith('\u309a') ? '一个小圆圈（半浊点）' : '两小笔（浊点）';
    return `先写「${base}」，再在右上角加${mark}。把「${base}」和「${glyph}」交替读一遍。`;
  }
  if (entry.group === 'combined') {
    const [base, small] = glyph;
    return `对比「${glyph}」和「${base}${String.fromCharCode(small.charCodeAt(0) + 1)}」。小假名和前一个假名合读一拍，写成大假名则分两拍读。`;
  }
  const reading = script === 'katakana' ? toKatakana(entry.reading) : entry.reading;
  return `圈出「${reading}」里的「${glyph}」，读一遍例词，再遮住假名写一遍。`;
}
